"""Safe, atomic Adobe Camera Raw (.xmp) preset compiler."""

import os
import uuid
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any, Dict, List
from xml.sax.saxutils import escape
from .schema import DEFAULT_CURVE, TONE_CURVE_KEYS, clamp_slider, sanitize_curve

RAW_EXTENSIONS = {".arw", ".cr2", ".cr3", ".nef", ".nrw", ".dng", ".raf", ".orf", ".rw2", ".pef"}


def build_xmp_xml(dna: Dict[str, Any], preset_name: str, group_name: str = "ChromaDNA") -> str:
    """Compile a Color DNA dictionary into a valid Adobe Camera Raw XMP string."""
    preset_uuid = uuid.uuid4().hex.upper()
    safe_name, safe_group = escape(preset_name), escape(group_name)
    sliders, curves = dna.get("sliders", {}), dna.get("tone_curves", {})
    attr_lines: List[str] = [
        '   crs:PresetType="Normal"', '   crs:Cluster=""', f'   crs:UUID="{preset_uuid}"',
        '   crs:SupportsAmount2="True"', '   crs:SupportsAmount="True"', '   crs:SupportsColor="True"',
        '   crs:SupportsMonochrome="True"', '   crs:SupportsHighDynamicRange="True"',
        '   crs:SupportsNormalDynamicRange="True"', '   crs:SupportsSceneReferred="True"',
        '   crs:SupportsOutputReferred="True"', '   crs:RequiresRGBTables="False"',
        '   crs:CameraModelRestriction=""', '   crs:Copyright="Generated by ChromaDNA"',
        '   crs:ContactInfo=""', '   crs:Version="15.0"', '   crs:ProcessVersion="15.4"',
        '   crs:HasSettings="True"',
    ]
    for key in sorted(sliders.keys()):
        val = clamp_slider(key, sliders[key])
        if val is not None:
            attr_lines.append(f'   crs:{key}="{val}"')
    curve_blocks: List[str] = []
    for ck in TONE_CURVE_KEYS:
        pts = sanitize_curve(curves.get(ck, DEFAULT_CURVE))
        li_items = "\n".join(f"     <rdf:li>{x}, {y}</rdf:li>" for x, y in pts)
        curve_blocks.append(f"   <crs:{ck}>\n    <rdf:Seq>\n{li_items}\n    </rdf:Seq>\n   </crs:{ck}>")
    attrs_joined, curves_joined = "\n".join(attr_lines), "\n".join(curve_blocks)
    xmp_content = f"""<x:xmpmeta xmlns:x="adobe:ns:meta/" x:xmptk="Adobe XMP Core 7.0-c000 1.000000, 0000/00/00-00:00:00">
 <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
  <rdf:Description rdf:about=""
    xmlns:crs="http://ns.adobe.com/camera-raw-settings/1.0/"
{attrs_joined}>
   <crs:Name>
    <rdf:Alt>
     <rdf:li xml:lang="x-default">{safe_name}</rdf:li>
    </rdf:Alt>
   </crs:Name>
   <crs:ShortName>
    <rdf:Alt>
     <rdf:li xml:lang="x-default">{safe_name}</rdf:li>
    </rdf:Alt>
   </crs:ShortName>
   <crs:SortName>
    <rdf:Alt>
     <rdf:li xml:lang="x-default">{safe_name}</rdf:li>
    </rdf:Alt>
   </crs:SortName>
   <crs:Group>
    <rdf:Alt>
     <rdf:li xml:lang="x-default">{safe_group}</rdf:li>
    </rdf:Alt>
   </crs:Group>
   <crs:Description>
    <rdf:Alt>
     <rdf:li xml:lang="x-default">Color DNA generated by ChromaDNA</rdf:li>
    </rdf:Alt>
   </crs:Description>
{curves_joined}
  </rdf:Description>
 </rdf:RDF>
</x:xmpmeta>
"""
    ET.fromstring(xmp_content)
    return xmp_content


def write_xmp_atomic(dna: Dict[str, Any], output_path: Path, preset_name: str, group_name: str = "ChromaDNA") -> Path:
    """Safely write an .xmp file atomically, preventing accidental overwrite of RAW sidecar files."""
    if output_path.suffix.lower() != ".xmp":
        output_path = output_path.with_suffix(".xmp")
    for raw_ext in RAW_EXTENSIONS:
        if output_path.with_suffix(raw_ext).exists() or output_path.with_suffix(raw_ext.upper()).exists():
            raise FileExistsError(
                f"Refusing to write '{output_path}': a RAW image with the same stem exists in this folder. "
                "Writing here would overwrite its sidecar edit history."
            )
    xml_str = build_xmp_xml(dna, preset_name=preset_name, group_name=group_name)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = output_path.with_suffix(f".{uuid.uuid4().hex[:8]}.tmp")
    tmp_path.write_text(xml_str, encoding="utf-8")
    os.replace(tmp_path, output_path)
    return output_path
